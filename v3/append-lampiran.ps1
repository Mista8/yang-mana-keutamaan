    <h4>Cara Menilai</h4>
    <p><strong>Kira YA untuk soalan ini: 2, 4, 6, 8, 10</strong> &mdash; ini adalah <strong>Multiplier tendencies</strong>.</p>
    <p><strong>Kira YA untuk soalan ini: 1, 3, 5, 7, 9</strong> &mdash; ini adalah <strong>Diminisher tendencies</strong>.</p>

    <table>
      <tr><th>Keputusan</th><th>Tafsiran</th></tr>
      <tr><td>Lebih banyak Multiplier (4-5 YA)</td><td>Kau secara semula jadi seorang Multiplier. Orang sekeliling rasa lebih bijak dan lebih mampu bila bersama kau.</td></tr>
      <tr><td>Campuran (2-3 setiap satu)</td><td>Kau mempunyai kedua-dua kecenderungan. Perhatikan situasi mana kau cenderung jadi Diminisher.</td></tr>
      <tr><td>Lebih banyak Diminisher (4-5 YA)</td><td>Kau mungkin secara tak sedar mengurangkan kecerdasan dan potensi orang sekeliling. Jangan risau &mdash; ini boleh diubah.</td></tr>
    </table>

