    <h3>Dari V1 &amp; V2...</h3>

    <p>Dari V1, kau dah belajar tentang Empat Kuadran &mdash; dan Kuadran II adalah tempat di mana kepimpinan sebenar berlaku. Bukan dalam keadaan panik last minute (Kuadran I), bukan dalam pelarian ke hiburan (Kuadran IV), tapi dalam ruang di mana kau ada masa untuk berfikir, membina hubungan, dan membuat keputusan strategik.</p>

    <p>Dari V2, kau dah belajar tiga skill kritikal: Seni Delegasi (supaya kau tak jadi bottleneck), Crucial Conversations (supaya kau boleh cakap benda susah tanpa rosakkan hubungan), dan Boundary Setting (supaya kau tak terbakar).</p>

    <p>Sekarang kita masuk ke V3 &mdash; buku penutup trilogi ini. Dan kita mulakan dengan satu kemahiran yang paling underrated dalam kepimpinan: <strong>coaching</strong>.</p>

    <hr>

    <h3>"Apa Kata Bos?"</h3>

    <p>Kau duduk dalam meeting room di tingkat 20 sebuah bangunan di KLCC. Di depan kau ada tujuh orang staf &mdash; masing-masing dengan muka serius. Kau baru je selesai bagi taklimat pasal target suku tahun ketiga.</p>

    <p>"Siapa ada soalan?" kau tanya. Sunyi.</p>

    <p>Baru kau nak bangun, Farid &mdash; staf yang dah tujuh tahun dalam team &mdash; angkat tangan. "Bos, saya nak tanya. Projek X tu macam mana kita nak handle? Deadline dia overlap dengan projek Y. Saya tak cukup orang."</p>

    <p>Dalam hati: <em>Dia ni tak boleh fikir ke?</em> Tapi kau senyum. "Farid, awak cuba buat macam ni: minta tolong pasukan A untuk handle sebahagian, and then shift priority untuk projek Y. Faham?"</p>

    <p>Farid mengangguk. Tapi dalam matanya, kau nampak satu cahaya yang pudar. Bukan cahaya terima kasih. Tapi cahaya kecewa. Dia nak kau percaya dia boleh fikir sendiri. Tapi kau tak bagi peluang.</p>

    <p>Ni antara detik paling kritikal dalam kepimpinan &mdash; dan kebanyakan kita gagal.</p>

    <hr>

    <h3>Kenapa Manager Gagal Jadi Coach</h3>

    <p>Michael Bungay Stanier, dalam buku <em>The Coaching Habit</em>, buat satu diagnosis yang menampar muka: <strong>Kita terlalu suka memberi nasihat.</strong></p>

    <p>Stanier panggil ni sebagai <strong>Advice Monster</strong> &mdash; raksasa dalam diri yang sentiasa nak memberi nasihat. Dan raksasa ni bahaya sebab mematikan inisiatif, mewujudkan dependency, membuang masa kau, dan tak develop next generation leaders.</p>

    <hr>

    <h3>Tujuh Soalan Coaching Power</h3>

    <h4>The Karpman Drama Triangle</h4>

    <p>Stephen Karpman jumpa satu pattern dalam perhubungan manusia yang dipanggil <strong>Drama Triangle</strong>. Ada tiga peranan:</p>

    <ol>
      <li><strong>Victim</strong> (Mangsa) &mdash; "Aku tak power la. Sistem ni tak adil."</li>
      <li><strong>Persecutor</strong> (Pendera) &mdash; "Ni semua salah kau!"</li>
      <li><strong>Rescuer</strong> (Penyelamat) &mdash; "Biar aku settlekan. Aku je yang boleh."</li>
    </ol>

    <p>Stanier kata: <strong>"The best way to escape the Drama Triangle is to stop giving advice."</strong></p>

    <hr>

    <h4>Soalan #1: The Kickstart Question</h4>
    <p><strong>"Apa yang ada dalam fikiran awak sekarang?"</strong></p>

    <h4>Soalan #2: The AWE Question</h4>
    <p><strong>"Dan apa lagi?"</strong> &mdash; <em>And What Else?</em></p>

    <h4>Soalan #3: The Focus Question</h4>
    <p><strong>"Apa cabaran sebenar di sini?"</strong></p>

    <h4>Soalan #4: The Foundation Question</h4>
    <p><strong>"Apa yang awak nak?"</strong></p>

    <h4>Soalan #5: The Lazy Question</h4>
    <p><strong>"Macam mana saya boleh bantu?"</strong></p>

    <h4>Soalan #6: The Strategic Question</h4>
    <p><strong>"Kalau awak cakap 'Ya' untuk ni, apa yang awak terpaksa cakap 'Tidak'?"</strong></p>

    <h4>Soalan #7: The Learning Question</h4>
    <p><strong>"Apa yang paling berguna dari perbualan kita ni?"</strong></p>

    <hr>

    <h3>Coaching dalam Budaya Hierarki Malaysia</h3>

    <p>Budaya kerja Malaysia adalah <strong>challenge</strong> untuk coaching model ni. Sebab senioriti, face, paternalistik, dan "tak selesa." Tapi sebenarnya, ni lah tempat di mana coaching <strong>paling diperlukan</strong>.</p>

    <p><strong>Cara adaptasi untuk Malaysia:</strong> Mulakan dengan konteks, guna pendekatan "kita", beri permission untuk jujur, praktis dengan isu kecil dulu, dan normalize "Aku tak tahu."</p>

    <hr>

    <h3>Tiga Perangkap Coaching yang Wajib Dielak</h3>

    <p><strong>Perangkap #1:</strong> Coaching Jadi Interogasi<br>
    <strong>Perangkap #2:</strong> Coaching Tanpa Tindakan<br>
    <strong>Perangkap #3:</strong> Coaching Hanya Untuk Masalah</p>

    <h3>Latihan Praktikal: 30 Hari Cabaran Coaching</h3>

    <p><strong>Minggu 1:</strong> Observe &mdash; Catat apa yang kau buat bila staf datang dengan masalah.<br>
    <strong>Minggu 2:</strong> Satu Soalan Sehari &mdash; Guna Kickstart Question setiap hari.<br>
    <strong>Minggu 3:</strong> Tiga "Dan Apa Lagi?" &mdash; Dalam setiap perbualan.<br>
    <strong>Minggu 4:</strong> Refleksi &amp; Komitmen &mdash; Tanya staf pasal perubahan kau.</p>

    <hr>

    <h3>Coaching untuk Diri Sendiri</h3>

    <p>Sebelum kau coach orang lain, kau kena coach diri sendiri. Setiap kali kau hadapi masalah, tanya diri: Apa yang ada dalam fikiran aku? Dan apa lagi? Apa cabaran sebenar? Apa yang aku nak? Macam mana aku boleh bantu diri sendiri? Kalau aku cakap Ya, apa yang aku kena cakap Tidak? Apa yang aku belajar?</p>

