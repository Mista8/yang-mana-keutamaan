    <h3>Membina Budaya Giving dalam Organisasi</h3>

    <p><strong>Langkah 1:</strong> Model Giving Dari Atas &mdash; Bagi kredit untuk orang lain. Bagi masa untuk mentoring.</p>
    <p><strong>Langkah 2:</strong> Ganjarkan Giving &mdash; Masukkan "collaboration" dalam KPI.</p>
    <p><strong>Langkah 3:</strong> Buang Takers &mdash; Satu Taker dalam team boleh racun seluruh budaya.</p>
    <p><strong>Langkah 4:</strong> Cipta Sistem &mdash; Skill-Sharing Friday, Help Wanted Channel, Gratitude Board.</p>
    <p><strong>Langkah 5:</strong> Ukur dan Raikan Giving &mdash; Peer recognition system.</p>
    <p><strong>Langkah 6:</strong> Cipta "Help-Seeking" Culture &mdash; Leader minta tolong secara terbuka.</p>

