    <h3>Dari V1 &amp; V2...</h3>

    <p>Dari V1, kau dah belajar bahawa kepimpinan bukan tentang kelajuan &mdash; tapi tentang arah. Empat Kuadran ajar kau untuk fokus pada apa yang <em>penting</em>, bukan apa yang <em>urgent</em>.</p>

    <p>Dari V2, kau dah belajar tiga pillar interpersonal: Crucial Conversations, Delegasi, dan Boundary Setting.</p>

    <p>Sekarang, kita akhiri trilogi ini dengan satu bab yang paling counter-intuitive. Selama ini kita diajar: "Dunia ni persaingan." Tapi Adam Grant jumpa satu kebenaran yang mengejutkan: <strong>Dalam jangka panjang, orang yang paling kerap memberi &mdash; Givers &mdash; adalah yang paling berjaya.</strong></p>

    <hr>

    <h3>Tiga Jenis Manusia</h3>

    <p><strong>Givers (Pemberi)</strong> &mdash; Memberi tanpa mengharap balasan. "Macam mana aku boleh bantu kau?"</p>
    <p><strong>Takers (Pengambil)</strong> &mdash; Ambil lebih dari apa yang dia bagi. "Apa yang aku dapat dari orang ni?"</p>
    <p><strong>Matchers (Penyeimbang)</strong> &mdash; Bagi setimpal dengan apa yang dia terima. "Awak tolong saya, saya tolong awak."</p>

    <hr>

    <h3>Kenapa Givers Ada di Atas dan di Bawah</h3>

    <p>Adam Grant jumpa satu penemuan yang counter-intuitive: <strong>Givers menduduki dua hujung ekstrem prestasi.</strong> Hujung teratas: Givers yang berjaya. Hujung terbawah: Givers yang terbakar dan dimanipulasi.</p>

    <p><strong>Kenapa ada Givers di bawah?</strong> Terlalu memberi sampai lupa diri, tak pandai kata "tidak", dimakan oleh Takers.</p>
    <p><strong>Kenapa ada Givers di atas?</strong> Mereka give strategically, protect themselves, dan expand the pie.</p>

    <hr>

    <h3>The 5-Minute Favor</h3>

    <p>Adam Grant ada satu konsep yang dipanggil <strong>The 5-Minute Favor</strong> &mdash; kau boleh buat perbezaan besar dalam hidup orang lain dengan meluangkan masa sesikit 5 minit.</p>

    <p><strong>Bentuk 5-Minute Favor:</strong> Introductions, sharing resources, mentoring ringkas, recommendations, feedback.</p>

    <hr>

    <h3>Self-Protective Giving &mdash; Rahsia Givers Yang Berjaya</h3>

    <p><strong>1. "Generous Triage"</strong> &mdash; Tak semua orang layak dapat bantuan kau. Triage macam doktor di emergency room.</p>

    <table>
      <tr><th>Kategori</th><th>Respons</th></tr>
      <tr><td>High need + High potential</td><td>Bagi sepenuh hati</td></tr>
      <tr><td>Low need + High potential</td><td>Bagi sikit &mdash; dorong dia buat sendiri</td></tr>
      <tr><td>High need + Low potential</td><td>Bagi asas &mdash; jangan over-invest</td></tr>
      <tr><td>Takers (confirmed)</td><td>Stop. Jangan bagi langsung</td></tr>
    </table>

    <p><strong>2. Boundary Giving</strong> &mdash; "Aku boleh bantu 15 minit. Lepas tu kena pergi."</p>
    <p><strong>3. Giving in Your Strength Zone</strong> &mdash; Jangan bagi dari kelemahan kau. Bagi dari kekuatan kau.</p>
    <p><strong>4. The "No, But..."</strong> &mdash; "No, I can't do that. But I can show you how."</p>
    <p><strong>5. The "Giver's Network"</strong> &mdash; Bina komuniti Givers.</p>

