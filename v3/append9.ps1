    <h3>Level 5 Leadership &mdash; Bos Yang Paling Bahaya Adalah Bos Yang Paling Rendah Hati</h3>

    <p>Jim Collins dan pasukan penyelidiknya menghabiskan 5 tahun mengkaji 1,435 syarikat. Hanya 11 yang berjaya beralih dari <em>good</em> ke <em>great</em>. Apa yang membezakan? Bukan strategi. Tapi <strong>kepimpinan</strong>.</p>

    <p><strong>Level 5 Leaders</strong> adalah gabungan <em>personal humility</em> (rendah hati) dan <em>professional will</em> (semangat kental).</p>

    <p><strong>Sisi 1: Rendah Hati (Humility)</strong> &mdash; Bila syarikat berjaya, mereka tunjuk ke luar: "Pasukan saya." Bila gagal, cermin ke dalam: "Saya yang bertanggungjawab."</p>

    <p><strong>Sisi 2: Keazaman Kental (Fierce Resolve)</strong> &mdash; Bila perlu, mereka boleh buat keputusan telanjang. <em>Lembut sebagai manusia, keras sebagai pemimpin.</em></p>

