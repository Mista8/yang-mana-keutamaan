    <h3>First Who, Then What &mdash; Orang Yang Tepat Dulu</h3>

    <p>Collins guna metafora bas. Pemimpin <em>great</em>: 1. First Who &mdash; Naikkan orang yang tepat. 2. Then What &mdash; Baru tentukan destinasi.</p>

    <p>Prinsip yang sama untuk hidup: <strong>Kau adalah purata 5 orang yang paling kerap kau luangkan masa dengan.</strong> Pilih circle kau dengan bijak.</p>

