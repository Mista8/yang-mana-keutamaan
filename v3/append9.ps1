    <h3>Stockdale Paradox</h3>

    <p>Laksamana James Stockdale, tawanan perang Vietnam selama 8 tahun, bertahan dengan satu prinsip:</p>

    <blockquote><p>"Kau tak boleh campur adukkan kepercayaan yang kau akan menang pada akhirnya &mdash; dengan disiplin untuk hadapi realiti paling brutal."</p></blockquote>

    <p><strong>Paradoks:</strong> Kepercayaan tak tergoyah + Kesediaan hadapi realiti paling pahit.</p>

