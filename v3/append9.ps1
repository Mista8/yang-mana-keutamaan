    <h3>The Hedgehog Concept</h3>

    <p>Persimpangan tiga soalan:</p>

    <ol>
      <li><strong>Apa yang kau boleh jadi TERBAIK di dunia?</strong></li>
      <li><strong>Apa yang buat kau BERSEMANGAT?</strong></li>
      <li><strong>Apa yang buat kau DAPAT DUIT?</strong></li>
    </ol>

    <p>Di persimpangan ketiga-tiga bulatan ni &mdash; di situlah <em>greatness</em> berada.</p>

    <hr>

    <h3>The Flywheel Effect</h3>

    <p>Syarikat <em>great</em> tak pernah buat transformasi secara dramatik. Perubahan berlaku perlahan-lahan &mdash; macam roda tenaga (flywheel). Setiap tolakan kecil menambah momentum. Tiba-tiba, pada satu titik &mdash; <em>breakthrough</em>.</p>

    <p>Greatness tak datang dari revolusi. Ia datang dari <strong>konsistensi yang berterusan</strong>.</p>

