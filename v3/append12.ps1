    <h3>Tema Besar Trilogi: Kenal Pasti &rarr; Hidup &rarr; Memimpin</h3>

    <p>Tiga buku. Tiga tema. Satu garis masa.</p>

    <p>Kalau kau lihat semula perjalanan ini, ada satu pola yang jelas. Setiap buku menjawab satu soalan asas:</p>

    <p><strong>V1: "Apa yang penting?"</strong> &mdash; <em>Kenal Pasti</em></p>

    <p>Buku pertama adalah tentang <strong>kesedaran</strong>. Kau belajar untuk membezakan antara yang urgen dan yang penting, antara yang mendesak dan yang bermakna. Kau belajar bahawa kebanyakan perkara yang kau risaukan sebenarnya tak penting. Kau belajar tentang kuasa fokus, tentang kesan kumulatif tabiat kecil, tentang kepentingan prinsip yang kukuh.</p>

    <p>Ini adalah fasa <strong>mengenal pasti</strong>. Macam kau berdiri di tengah hutan dan akhirnya tahu arah mana nak tuju.</p>

    <p><strong>V2: "Macam mana nak lindungi apa yang penting?"</strong> &mdash; <em>Hidup</em></p>

    <p>Buku kedua adalah tentang <strong>pelaksanaan dan perlindungan</strong>. Bila kau dah tahu apa yang penting, sekarang kau kena belajar untuk melindunginya. Kau belajar untuk berkata tidak tanpa rasa bersalah. Kau belajar untuk urus tenaga, bukan sekadar masa. Kau belajar untuk bercakap tentang perkara sukar, untuk mewakilkan, untuk membina legasi.</p>

    <p>Ini adalah fasa <strong>hidup dengan keutamaan</strong>. Kau dah mula berjalan ke arah yang kau pilih.</p>

    <p><strong>V3: "Macam mana nak bawa orang lain bersama?"</strong> &mdash; <em>Memimpin</em></p>

    <p>Buku ketiga ini adalah tentang <strong>impak dan penggandaan</strong>. Bila kau dah boleh pimpin diri sendiri, sekarang kau pimpin orang lain. Kau belajar tentang kecerdasan emosi, tentang menjadi pemimpin yang melipatgandakan kecerdasan team, tentang memberi dan mempengaruhi, tentang membina sistem yang hidup lebih lama daripada kau.</p>

    <p>Ini adalah fasa <strong>memimpin dan mewariskan</strong>.</p>

