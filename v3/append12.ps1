    <h3>Dari V1 &amp; V2 ke V3: Satu Perjalanan, Tiga Langkah</h3>

    <p>Tiga buku. Tiga puluh enam bab. Lebih setahun penulisan, penelitian, dan renungan.</p>

    <p>Kalau kau baca buku ini tanpa tahu V1 dan V2, jangan risau &mdash; kau tak ketinggalan. Buku ketiga ini memang direka untuk berdiri sendiri. Tapi untuk betul-betul faham kenapa trilogi ini wujud, dan untuk kau dapat memanfaatkan bab akhir ini sepenuhnya, izinkan saya bawa kau melihat semula perjalanan penuh.</p>

    <h4>V1: "Yang Mana Keutamaan?" &mdash; Mengenali (Act 1-3)</h4>

    <p>Buku pertama lahir daripada satu pertanyaan mudah yang kita semua pernah hadapi: <em>"Kenapa aku sibuk sangat tapi tak ada apa-apa yang selesai?"</em></p>

    <p>Kita hidup dalam dunia yang menjerit pada kita setiap saat. Notifikasi. Emel. Group chat pejabat yang berbunyi pukul 11 malam. Tuntutan dari bos, dari keluarga, dari kawan, dari diri sendiri. Semua nak perhatian kita. Semua rasa penting.</p>

    <p>V1 adalah buku tentang <strong>memilih</strong>. Bukan tentang buat lebih, tapi tentang buat lebih sedikit &mdash; dengan lebih fokus.</p>

    <p><strong>Act 1: Mengenali Masalah</strong> &mdash; Kita mulakan dengan faham kenapa kita rasa tertekan. Clock vs Compass: kau sibuk tapi entah ke mana. Balang Kehidupan: batu besar vs pasir. Empat Kuadran: urgen vs penting. Sebelum kau boleh ubah apa-apa, kau kena faham apa yang tak kena.</p>

    <p><strong>Act 2: Memahami Keutamaan</strong> &mdash; Lepas faham masalah, kau kena ada alat untuk bezakan yang penting dari yang tak penting. Essentialism: buat lebih sedikit tapi lebih baik. The One Thing: apa satu benda yang buat segala-galanya lebih mudah atau tak perlu? Circle of Influence: jangan bazir tenaga pada apa yang kau tak kuasai.</p>

    <p><strong>Act 3: Melaksanakan</strong> &mdash; Tahu mana keutamaan tak guna kalau kau tak buat. Deep Work: fokus dalam dunia yang penuh gangguan. Atomic Habits: perubahan kecil, hasil besar. Habit Loop: faham psikologi sebalik tabiat. Sharpen the Saw: jaga diri sendiri. Prinsip &amp; Purpose: hidup berlandaskan sesuatu yang lebih besar.</p>

    <p>V1 berakhir dengan satu pelan 30 hari. Tiga puluh hari untuk mula berubah. Untuk mula hidup dengan keutamaan, bukan dengan reaksi.</p>

    <h4>V2: "Yang Mana Keutamaan? &mdash; Melangkah Lebih Jauh" (Act 1-3)</h4>

    <p>Tapi 30 hari tak cukup. Kau boleh mula dalam 30 hari, tapi transformasi sebenar memerlukan lebih masa, lebih kedalaman, lebih banyak kemahiran.</p>

    <p>V2 adalah buku tentang <strong>memperdalam</strong>. Bila kau dah boleh pilih keutamaan, sekarang kau kena belajar untuk melindungi dan mengembangkan keupayaan kau.</p>

    <p><strong>Act 1: Melindungi Masa &amp; Tenaga</strong> &mdash; Seni Berkata Tidak: sempadan yang melindungi keutamaan kau. Decision Fatigue: kenapa terlalu banyak pilihan melemahkan kau. Mental Models: cara berfikir yang lebih tajam.</p>

    <p><strong>Act 2: Mengoptimumkan Prestasi</strong> &mdash; Flow State: prestasi puncak tanpa usaha. Energy Management: masa tak penting kalau kau tak ada tenaga. Digital Minimalism: teknologi sebagai alat, bukan tuan.</p>

    <p><strong>Act 3: Meluaskan Impak</strong> &mdash; Seni Delegasi: kau tak boleh buat semuanya sendiri. Start With Why: tujuan sebagai bahan api. Crucial Conversations: bercakap pasal benda sukar. Antifragile: jadi lebih kuat dari setiap cabaran. Legacy Thinking: apa yang kau nak tinggalkan?</p>

    <p>V2 berakhir dengan Pelan 100 Hari. Satu rangka masa yang lebih panjang untuk benar-benar membina kehidupan yang selaras dengan keutamaan kau.</p>

