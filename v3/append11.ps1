    <h3>Cerita Pembuka: Malam Itu di Dapur Kecil</h3>

    <p>Aku kenal seorang &mdash; panggil je nama dia Mat. Mat kerja sebagai kerani di sebuah pejabat kerajaan di Putrajaya. Tapi setiap malam, lepas Isyak, Mat duduk di depan komputer lama dan dia menulis cerita. Dia menulis dengan penuh semangat, kadang-kadang sampai pukul 3 pagi.</p>

    <p>Mat ada impian: nak jadi penulis. Tapi Mat tak pernah hantar mana-mana cerita dia ke penerbit. "Sekadar hobi." "Lepas ni." "Kalau tak laku, malu."</p>

    <p>Tahun demi tahun. Mat terus menulis. Tapi Mat tak pernah <em>menjadi</em> penulis. Hard disk itu satu hari nanti rosak. Dan dengan itu, lenyaplah beribu-ribu jam kerja.</p>

    <p>Mat bukan sorang. Kita semua ada Mat dalam diri kita. Suara yang kata: "Belum ready lagi." "Nanti dulu."</p>

    <p>Inilah yang Steven Pressfield panggil <strong>Resistance</strong>. Dan satu-satunya cara untuk mengalahkan Resistance? <strong>Turn Pro.</strong></p>

    <hr>

    <h3>Resistance &mdash; Musuh Paling Senyap</h3>

    <p>Steven Pressfield, dalam bukunya <em>The War of Art</em>, memperkenalkan satu konsep yang paling penting: <strong>Resistance</strong>. Bukan musuh luar. Tapi musuh <strong>dalam</strong>.</p>

    <p><strong>Macam mana Resistance bunyi?</strong></p>
    <ul>
      <li>Bila kau nak mula menulis: "Buka Facebook kejap."</li>
      <li>Bila kau nak bersenam: "Hari ni hujan. Esok je lah."</li>
      <li>Bila kau nak apply kerja idaman: "Kau qualified ke?"</li>
    </ul>

    <p><strong>Bentuk-bentuk Resistance:</strong> Prokrastinasi, Perfectionism, Self-Doubt, Distraction, Busy-ness, Comparison.</p>

    <p>Pressfield kata: <strong>"The more important a call or action is to our soul's evolution, the more Resistance we will feel."</strong> Makin besar potensi kau, makin kuat Resistance.</p>

    <hr>

    <h3>Amatur vs Professional</h3>

    <table>
      <tr><th>Amatur</th><th>Profesional</th></tr>
      <tr><td>Main-main</td><td>Serious</td></tr>
      <tr><td>Bila ada mood</td><td>Setiap hari</td></tr>
      <tr><td>Tunggu inspirasi</td><td>Buat kerja walau takde mood</td></tr>
      <tr><td>Takut kritik</td><td>Guna kritik untuk maju</td></tr>
      <tr><td>Berhenti bila susah</td><td>Teruskan walau apa pun</td></tr>
      <tr><td>Nak pengiktirafan</td><td>Nak hasil yang bermakna</td></tr>
    </table>

