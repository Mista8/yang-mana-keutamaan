    <h3>Turning Pro: Satu Keputusan, Bukan Proses</h3>

    <p>Pressfield tekankan: <strong>Turning pro bukan proses. Ia keputusan.</strong> Satu detik. Bukan "saya akan jadi pro dalam 6 bulan." Tapi "Mulai saat ini, saya adalah pro."</p>

    <p><strong>Tanda kau dah turn pro:</strong></p>
    <ul>
      <li>Kau berhenti cakap "saya try" dan mula cakap "saya buat"</li>
      <li>Kau berhenti bagi alasan</li>
      <li>Kau terima bahawa 90% adalah tentang persembahan &mdash; bukan perasaan</li>
      <li>Kau fokus pada proses, bukan hasil</li>
      <li>Kau tak tunggu pengiktirafan</li>
    </ul>

    <hr>

    <h3>Professional Habits &mdash; Ritual Harian</h3>

    <p>Pro tak tunggu motivasi. Pro ada <strong>ritual</strong>.</p>

    <p><strong>Ritual Seorang Penulis:</strong> 5:00 pagi bangun, kopi, mula menulis 5:30, selesai 7:30. Setiap hari.</p>
    <p><strong>Ritual Seorang Usahawan:</strong> Senaman 6 pagi, review sasaran 7 pagi, buat kerja paling penting dulu sebelum buka email.</p>

    <p><strong>Prinsip Ritual Pro:</strong> Konsisten bukan intensiti. Mula dengan kemenangan kecil. Hilangkan friction. Lindungi ritual dengan garisan tegas.</p>

    <hr>

    <h3>7 Langkah Turning Pro</h3>
    <p><strong>Langkah 1:</strong> Kenali Resistance &mdash; Apa yang kau paling takut nak buat? Itulah petunjuk panggilan kau.<br>
    <strong>Langkah 2:</strong> Buat Keputusan &mdash; Tulis: "Mulai hari ini, aku adalah seorang [pro dalam bidang apa]."<br>
    <strong>Langkah 3:</strong> Bina Ritual Harian &mdash; Pilih satu ritual, konsisten lebih penting dari tempoh.<br>
    <strong>Langkah 4:</strong> Sediakan Ruang Kerja &mdash; Tempat khusus untuk kerja pro kau.<br>
    <strong>Langkah 5:</strong> Hapuskan Gangguan &mdash; Telefon silent, social media block.<br>
    <strong>Langkah 6:</strong> Accept It's a Long Game &mdash; Pro tak jadi pro dalam seminggu.<br>
    <strong>Langkah 7:</strong> Cari Komuniti Pro &mdash; Mereka faham perjuangan kau.</p>

