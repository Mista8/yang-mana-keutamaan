    <h3>The Multiplier: Lima Disiplin</h3>

    <p><strong>Disiplin #1: The Talent Magnet</strong> &mdash; Multiplier tarik bakat &mdash; dan guna mereka sepenuhnya. "Aku nampak kau pandai buat presentasi. Kau nak lead session client next week?"</p>

    <p><strong>Disiplin #2: The Liberator</strong> &mdash; Multiplier cipta persekitaran di mana orang rasa selamat untuk berfikir. "Kita nak cuba approach baru. Kalau gagal, kita belajar. Aku janji takkan marah."</p>

    <p><strong>Disiplin #3: The Challenger</strong> &mdash; Multiplier regangkan orang &mdash; dan percaya yang mereka boleh capai lebih. Guna "stretch assignments" dan "The Question": "What would you do if you weren't afraid?"</p>

    <p><strong>Disiplin #4: The Debate Maker</strong> &mdash; Multiplier guna percanggahan pendapat untuk hasilkan keputusan yang lebih baik. "Siapa nak jadi devil's advocate?"</p>

    <p><strong>Disiplin #5: The Investor</strong> &mdash; Multiplier melabur dalam orang &mdash; dan bagi mereka ownership. Guna "70% rule" &mdash; kalau staf boleh buat 70% sebaik kau, bagi dia.</p>

