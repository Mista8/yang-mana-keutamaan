    <h3>The Diminisher: Kenapa Dia Tak Sedar</h3>

    <p><strong>1. The Genius Maker</strong> &mdash; Dia rasa dia orang paling pandai dalam bilik. Kesan: Staf berhenti berfikir.</p>
    <p><strong>2. The Know-It-All</strong> &mdash; Dia selalu ada jawapan. Kesan: Staf jadi pasif dan dependent.</p>
    <p><strong>3. The Decision Maker</strong> &mdash; Semua keputusan mesti melalui dia. Kesan: Bottleneck.</p>
    <p><strong>4. The Micro-Manager</strong> &mdash; Dia nak tahu setiap detail. Kesan: Autonomy = sifar.</p>

    <p>Dan yang paling ironik: <strong>Diminisher rasa dia tengah buat kerja dengan baik.</strong> Sebab "Aku detail-oriented" dan "Aku maintain standard."</p>

