    <h3>Dua Jenis Pemimpin</h3>

    <p>Liz Wiseman, dalam buku <em>Multipliers</em>, jumpa dua pola:</p>

    <p><strong>The Diminisher:</strong> Pemimpin yang mengecutkan kecerdasan orang sekeliling. Bila dia masuk bilik, IQ semua orang turun 20 mata.</p>

    <p><strong>The Multiplier:</strong> Pemimpin yang menggandakan kecerdasan orang sekeliling. Bila dia masuk bilik, IQ semua orang naik 20 mata.</p>

    <p>Yang mengejutkan: <strong>Kebanyakan Diminishers tak sedar yang mereka Diminishers.</strong></p>

