      <tr><td><strong>Impact</strong></td><td>"...aku perasan muka dia berubah. Kita hampir hilang kepercayaan dia."</td></tr>
    </table>

    <p><strong>Langkah 4:</strong> The Art of Receiving Feedback &mdash; Dengar dulu, ucap terima kasih, tanya untuk clarify, ambil masa untuk proses, follow up.</p>

