    <h3>Cara Nak Bagi Feedback Pedas Tapi Diterima</h3>

    <p><strong>Langkah 1:</strong> Check Niat Kau &mdash; Nak membantu dia berkembang? Atau nak lepaskan geram?</p>
    <p><strong>Langkah 2:</strong> "I'm About to Give You Some Feedback" &mdash; Bagi heads-up. Jangan terus terjah.</p>
    <p><strong>Langkah 3:</strong> Guna SBI Framework (Situation, Behavior, Impact)</p>

    <table>
      <tr><th>Komponen</th><th>Contoh</th></tr>
      <tr><td><strong>Situation</strong></td><td>"Semalam dalam meeting dengan klien..."</td></tr>
